/**
 * Writes the suite colour tokens into app/globals.css from design/suite-tokens.json, a copy of
 * UAOP's docs/04_UI_Architecture/SUITE_TOKENS.json shared with FlightMD and the UAOP GCS. Only
 * the lines between the BEGIN/END markers in `:root` (dark) and `.light` are rewritten; tokens
 * the suite file doesn't have (zones, danger-solid, on-accent, motion) stay hand-written.
 *
 *   node scripts/gen-tokens.mjs          rewrite globals.css
 *   node scripts/gen-tokens.mjs --check  exit 1 when globals.css is out of date
 */
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const tokensPath = path.join(here, "..", "design", "suite-tokens.json");
const cssPath = path.join(here, "..", "app", "globals.css");

const BEGIN = "/* BEGIN generated by scripts/gen-tokens.mjs from design/suite-tokens.json -- do not edit */";
const END = "/* END generated */";

// CSS variable -> suite token, in the order they are written
const MAP = [
  ["bg", "bg0"],
  ["surface", "bg1"],
  ["elevated", "bg2"],
  ["border", "stroke"],
  ["text", "fg0"],
  ["text-muted", "fg1"],
  ["text-subtle", "fg2"],
  ["accent", "accent"],
  ["accent-solid", "accentSolid"],
  ["accent-text", "accentText"],
  ["warn", "cautionAmber"],
  ["danger", "warnRedText"],
  ["ok", "okGreen"],
];

const NOTES = {
  "text-subtle": "Only for disabled text or text >= 18 px.",
  accent: "focus, icons, selection",
  warn: "Status: always paired with an icon and a label",
  danger: "text and icons; fills use --danger-solid",
};

// AirBrief keeps its brighter light-theme focus ring and links (both over 4.5:1 on every
// light surface, checked by tests/frontend/test_tokens.py)
const OVERRIDES = { light: { accent: "#2563eb", "accent-text": "#1d4ed8" } };

function rgb(hex) {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
}

function block(theme, values, indent) {
  const lines = [indent + BEGIN];
  for (const [name, token] of MAP) {
    const hex = String(OVERRIDES[theme]?.[name] ?? values[token] ?? "").toLowerCase();
    if (!/^#[0-9a-f]{6}$/.test(hex)) throw new Error(`${theme}.${token}: missing, or not a #rrggbb colour`);
    if (NOTES[name]) lines.push(`${indent}/* ${NOTES[name]} */`);
    lines.push(`${indent}--${name}: ${hex};`, `${indent}--${name}-rgb: ${rgb(hex)};`);
  }
  lines.push(indent + END);
  return lines;
}

function replaceBlock(lines, theme, values, from) {
  const start = lines.findIndex((l, i) => i >= from && l.trim() === BEGIN);
  const stop = lines.findIndex((l, i) => i > start && l.trim() === END);
  if (start < 0 || stop < 0) throw new Error(`globals.css: no generated block for the ${theme} theme`);
  const indent = lines[start].slice(0, lines[start].indexOf("/*"));
  lines.splice(start, stop - start + 1, ...block(theme, values, indent));
  return start + 1;
}

const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));
const current = readFileSync(cssPath, "utf8");
const lines = current.split("\n");
// :root (dark) comes first in the file, then .light
const next = replaceBlock(lines, "dark", tokens.themes.dark, 0);
replaceBlock(lines, "light", tokens.themes.light, next);
const updated = lines.join("\n");

if (process.argv.includes("--check")) {
  if (updated !== current) {
    console.error("app/globals.css is out of date: run node scripts/gen-tokens.mjs");
    process.exit(1);
  }
} else if (updated !== current) {
  writeFileSync(cssPath + ".tmp", updated);
  renameSync(cssPath + ".tmp", cssPath);
  console.log("Wrote the suite tokens into app/globals.css");
}
